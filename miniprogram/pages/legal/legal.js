Page({
  data: {
    pageAnim: false,
    type: 'terms',
    doc: DOCS.terms,
    tabIndex: 0,
    indStyle: '',
    supportEmail: config.supportEmail,
    tabs: [
      { key: 'terms', label: '用户协议' },
      { key: 'privacy', label: '隐私政策' },
      { key: 'ai', label: 'AI 说明' },
    ],
  },

  onLoad(q) {
    this.switchTo(q.type || 'terms');
  },

  onShow() {
    motion.enter(this);
  },

  onHide() {
    motion.clear(this);
  },

  onUnload() {
    this.__gone = true;
    motion.clear(this);
  },

  switchDoc(e) {
    this.switchTo(e.currentTarget.dataset.type);
  },

  switchTo(type) {
    const doc = DOCS[type] || DOCS.terms;
    const idx = Math.max(0, this.data.tabs.findIndex((t) => t.key === type));
    this.setData({
      type,
      doc,
      tabIndex: idx,
      indStyle: motion.segStyle(idx, this.data.tabs.length),
    });
    wx.setNavigationBarTitle({ title: doc.title });
    wx.pageScrollTo({ scrollTop: 0, duration: 0 });
  },

  copySupport() {
    wx.setClipboardData({
      data: config.supportEmail,
      success: () => wx.showToast({ title: '邮箱已复制', icon: 'none' }),
    });
  },

  onShareAppMessage() {
    return { title: `网剧大咖 · ${this.data.doc.title}`, path: '/pages/index/index' };
  },
});
