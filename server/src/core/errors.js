export class AppError extends Error {
  /**
   * @param {string} code 见 ERR
   * @param {string} message 面向用户的中文说明
   * @param {object} [detail] 内部结构化的排查信息（不下发敏感值）
   */
  constructor(code, message, detail = {}) {
    super(message);
    this.name = 'AppError';
    this.code = code;
    this.detail = detail;
    this.status = HTTP_STATUS[code] ?? 400;
  }

  toJSON() {
    return { ok: false, code: this.code, message: this.message, detail: sanitize(this.detail) };
  }
}

/** 详情里也不许带敏感键 */
const SENSITIVE = /apikey|api_key|password|secret|token|authorization/i;
function sanitize(obj, depth = 0) {
  if (depth > 4 || obj === null || typeof obj !== 'object') return obj;
  if (Array.isArray(obj)) return obj.slice(0, 50).map((v) => sanitize(v, depth + 1));
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    out[k] = SENSITIVE.test(k) ? '***' : sanitize(v, depth + 1);
  }
  return out;
}

export function fail(code, message, detail) {
  throw new AppError(code, message, detail);
}
